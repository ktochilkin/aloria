            ]),
            _ => ($"Новости {name}", "Событие экономического мира Алории."),
        };
    }

    // Отчётность: три исхода по сюрпризу, по паре вариантов на каждый.
    private (string, string) Earnings(EventSpec spec, string name)
    {
        var z = spec.SurpriseZ ?? 0;
        if (z > 0.7)
            return Pick([
                ($"{name} обошла прогнозы",
                    $"Прибыль {name} — {Fmt(spec.Actual)} на акцию против ожидавшихся {Fmt(spec.Expected)}: аналитикам придётся переписывать модели. Менеджмент сдержанно доволен, инвесторы — не сдержанно. Одно «но»: чем громче сюрприз, тем выше планка на следующий квартал."),
                ($"Отчёт {name}: лучше, чем ждали",
                    $"{name} заработала {Fmt(spec.Actual)} на акцию — консенсус в {Fmt(spec.Expected)} остался позади. Разбор полётов показывает: сработали и выручка, и дисциплина в издержках. Теперь главный вопрос — сколько из этого рынок успел заложить заранее."),
            ]);
        if (z < -0.7)
            return Pick([
                ($"{name} не дотянула до прогнозов",
                    $"Прибыль {name} — {Fmt(spec.Actual)} на акцию при консенсусе {Fmt(spec.Expected)}: промах, который не спрячешь в сносках. Менеджмент ссылается на издержки и обещает исправиться. Рынок выслушал — и переоценил ожидания вниз."),
                ($"Слабый отчёт {name}",
                    $"{name} показала {Fmt(spec.Actual)} на акцию — аналитики ждали {Fmt(spec.Expected)}. Где-то просела выручка, где-то распухли расходы; подробности в разборе, осадок уже в котировках. Следующий отчёт станет проверкой на характер."),
            ]);
        return Pick([
            ($"{name}: без сюрпризов",
                $"Результат {name} — {Fmt(spec.Actual)} на акцию, практически в яблочко консенсуса {Fmt(spec.Expected)}. Скучный отчёт — недооценённый жанр: бизнес предсказуем, менеджмент держит слово. А раз сюрприза нет — нет и повода для резких движений."),
            ($"Отчёт {name} совпал с ожиданиями",
                $"{name} заработала {Fmt(spec.Actual)} на акцию — рынок именно это и закладывал ({Fmt(spec.Expected)}). Хрестоматийная иллюстрация: цена двигается на отклонении от ожиданий, а не на самом факте прибыли. Отклонения нет — и стрелка почти не дрогнула."),
        ]);
    }

    private (string, string) Dividend(EventSpec spec, string name)
    {
        if (spec.Sign < 0 && (spec.Actual ?? 0) < (spec.Expected ?? 1) * 0.6)
            return Pick([
                ($"{name} режет дивиденды",
                    $"Совет директоров {name} урезал выплату до {Fmt(spec.Actual)} на акцию — деньги нужнее внутри компании. Для дивидендных инвесторов это болезненный сигнал: обещанная «зарплата от портфеля» похудела. С другой стороны, устойчивость бизнеса важнее щедрости на один цикл."),
                ($"Дивидендный сюрприз {name} — со знаком минус",
                    $"{name} объявила {Fmt(spec.Actual)} на акцию вместо привычных цифр — баланс требует бережности. Кто-то выйдет из бумаги, кто-то поверит менеджменту на слово. Урок простой: дивиденды — не гарантия, а решение, которое пересматривают."),
            ]);
        if (spec.Sign > 0)
            return Pick([
                ($"{name} повышает дивиденды",
                    $"Совет директоров {name} рекомендовал {Fmt(spec.Actual)} на акцию — щедрее, чем ждал рынок. Такая уверенность обычно означает, что с денежным потоком всё в порядке. Отсечка завтра: успевают те, кто в реестре."),
                ($"Акционерам {name} добавили",
                    $"{name} объявила выплату {Fmt(spec.Actual)} на акцию, приятно удивив держателей. Дивидендная история компании становится всё убедительнее. Дальше по расписанию: отсечка, выплата, и деньги на счетах."),
            ]);
        return Pick([
            ($"{name} объявила дивиденды",
                $"Совет директоров {name} рекомендовал {Fmt(spec.Actual)} на акцию — в русле ожиданий. Реестр закроется завтра, выплата через день: в сжатом времени Алории всё происходит быстро. Стабильность — тоже новость, просто тихая."),
            ($"Дивиденды {name}: по плану",
                $"{name} подтвердила выплату {Fmt(spec.Actual)} на акцию, без сюрпризов в обе стороны. Инвесторы кивнули и вернулись к делам. Предсказуемость дивидендной политики — недооценённая добродетель."),
        ]);
    }

    private (string, string) Rate(EventSpec spec, WorldSnapshot w)
    {
        var d = spec.Actual ?? 0;
        var surprise = Math.Abs((spec.Actual ?? 0) - (spec.Expected ?? 0)) >= 0.01;
        var tail = surprise
            ? "Решение разошлось с консенсусом — а сюрпризы от регулятора рынок отыгрывает резко: смотри на банки и закредитованные компании, им ставка небезразлична по-разному."
            : "Рынок такой шаг и закладывал, так что бурной реакции не ждём: всё уже было в ценах. Учебный момент: даже большое событие без сюрприза — маленькая новость.";
        if (d > 0)
            return ("ЦБ Алории повысил ставку",
                $"Регулятор поднял ключевую ставку на {d:0.##} п.п., до {w.KeyRate:0.##}% — борьба с инфляцией продолжается. Деньги в Алории стали дороже: кредиты тяжелее, облигации с фиксированным купоном пересчитываются вниз. {tail}");
        if (d < 0)
            return ("ЦБ Алории снизил ставку",
                $"Регулятор опустил ключевую ставку на {Math.Abs(d):0.##} п.п., до {w.KeyRate:0.##}% — экономике дают дешёвых денег. Кредиты доступнее, у облигаций праздник переоценки. {tail}");
        return ("ЦБ Алории оставил ставку без изменений",
            $"Ключевая ставка сохранена на {w.KeyRate:0.##}% — регулятор взял паузу и наблюдает. Формулировки пресс-релиза разобрали на цитаты в поисках намёков. {tail}");
    }

