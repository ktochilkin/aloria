namespace Aloria.Director.Core.News;

/// <summary>
/// Шаблонный нарратор — офлайн-fallback и основной рассказчик без LLM-ключа.
/// Пулы вариантов на каждый тип события + «казусы» (spec.Quirky): Алория —
/// игровой мир, новости можно читать с удовольствием. Последствия всегда
/// рыночно-реалистичные; собственный RNG нарратора влияет только на текст,
/// не на экономику (просчёт будущего от него не зависит).
/// </summary>
public sealed class TemplateNarrator : INarrator
{
    private readonly Rng _rng;

    public TemplateNarrator(Rng rng) => _rng = rng;

    public Task<NewsStory> NarrateAsync(NewsDraft draft, CancellationToken ct = default)
        => Task.FromResult(Narrate(draft));

    public NewsStory Narrate(NewsDraft draft)
    {
        var spec = draft.Spec;
        var symbol = spec.Symbol
                     ?? (spec.CandidateSymbols.Count > 0 ? _rng.Pick(spec.CandidateSymbols) : null);
        var issuer = symbol is not null ? Universe.Issuers.FirstOrDefault(i => i.Symbol == symbol) : null;
        var bond = symbol is not null && issuer is null
            ? Universe.Bonds.FirstOrDefault(b => b.Symbol == symbol)
            : null;
        var name = issuer?.Name ?? bond?.Name ?? symbol ?? "рынок";
        var theme = issuer?.Theme ?? "бизнес";

        var (headline, body) = Compose(spec, name, theme, draft.World);
        var sentiment = spec.Type is EventType.Coupon or EventType.DividendPayout
            ? Sentiment.Neutral
            : spec.Sign > 0 ? Sentiment.Positive
            : spec.Sign < 0 ? Sentiment.Negative
            : Sentiment.Neutral;

        return new NewsStory
        {
            Headline = headline,
            Body = body,
            Sentiment = sentiment,
            ChosenSymbol = symbol,
        };
    }

    private (string, string) Pick(IReadOnlyList<(string H, string B)> pool) => _rng.Pick(pool);

