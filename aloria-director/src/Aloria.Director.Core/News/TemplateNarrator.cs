                    $"{name} вводит новые мощности и нанимает людей — заявка на рост доли рынка. Инвесторы любят экспансию, когда она окупается, и не любят, когда она съедает кассу. Менеджмент уверяет, что просчитал всё дважды."),
            ]),
            EventType.OperationsShock => Pick([
                ($"Сбой в работе {name}",
